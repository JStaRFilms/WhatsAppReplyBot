test('generated punctuation covers each prose variant without touching IDs or emoji', () => {
  const cases = [
    ['a\u2014b','a, b'],['a \t\u2014 \tb','a, b'],['a\u2014\u2014b','a, , b'],
    ['\u2014a',', a'],['a\u2014','a,'],['a\n\u2014\nb','a\n, \nb'],['🙂\u2014é','🙂, é'],
  ];
  for (const [input,expected] of cases) {
    const action = normalizeGeneratedAction({kind:'text',text:input ?? '',reason:'why\u2014yes'});
    assert.equal(action.kind === 'text' && action.text,expected); assert.equal(action.reason,'why, yes');
  }
  for (const kind of ['silence','handover','reaction','reaction_plus_text','text_sequence'] as const) {
    const action: Action = kind === 'text_sequence' ? {kind,messages:[{text:'a\u2014b',quotedMessageId:'quote\u2014id'},{text:'c\u2014d'}],reason:'r\u2014s'}
      : kind === 'reaction_plus_text' ? {kind,text:'a\u2014b',reaction:{targetMessageId:'target\u2014id',emoji:'🙂'},reason:'r\u2014s'}
      : kind === 'reaction' ? {kind,reaction:{targetMessageId:'target\u2014id',emoji:'🙂'},reason:'r\u2014s'} : {kind,reason:'r\u2014s'};
    const normalized = normalizeGeneratedAction(action);
    assert.equal(normalized.reason,'r, s');
    if (normalized.kind === 'text_sequence') {
      assert.deepEqual(normalized.messages.map(m => m.text),['a, b','c, d']);
      assert.equal(normalized.messages[0]?.quotedMessageId,'quote\u2014id');
    }
    if ('reaction' in normalized) assert.deepEqual(normalized.reaction,{targetMessageId:'target\u2014id',emoji:'🙂'});
    if ('text' in normalized) assert.equal(normalized.text,'a, b');
  }
});

